"""Hash-pinned loading of the team's original official 333-row CLIP text bank."""
import hashlib
import os
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OFFICIAL_BANK_SHA256='1e1183371b7ad3b1687f7a140af1fea89e1fa6744ac98f1a30ad6fdae19be22b'
OFFICIAL_FEATURES_SHA256='5bbb5f715620c65fa76b2f32c84b72dddf0d9ceae8d43c7e9720a2240ff999b6'
OFFICIAL_BANK_URL='https://drive.google.com/file/d/1DKvZo__aQyvW1M2QOwu661KdKOv8CHWw/view'


def locate_official_text_bank():
    supplied=os.environ.get('LEAFLENS_CLIP_TEXT_BANK')
    if supplied:
        path=Path(supplied).expanduser()
        if not path.is_file():
            raise FileNotFoundError('LEAFLENS_CLIP_TEXT_BANK does not point to an existing file')
        return path
    choices=(ROOT/'models/official333_clip_text_bank.npz',
             ROOT/'runs/wp4-official-bank-20261112/official333_text_bank.npz')
    for path in choices:
        if path.is_file():
            return path
    raise FileNotFoundError('Supply the official 333-row bank in models/official333_clip_text_bank.npz '
                            'or set LEAFLENS_CLIP_TEXT_BANK. No bank is downloaded or regenerated by the GUI.')


def load_official_text_bank(path=None):
    import numpy as np
    import torch
    from final_protocol import file_sha256
    path=Path(path) if path is not None else locate_official_text_bank()
    before=file_sha256(path)
    if before!=OFFICIAL_BANK_SHA256:
        raise ValueError('Official CLIP text-bank file SHA-256 mismatch')
    with np.load(path,allow_pickle=False) as archive:
        if set(archive.files)!={'features','candidate_ids'}:
            raise ValueError('Unexpected official text-bank fields')
        features=archive['features']
        ids=archive['candidate_ids']
        if ids.dtype!=np.int64 or not np.array_equal(ids,np.arange(333,dtype=np.int64)):
            raise ValueError('Official text-bank candidate columns or ID types differ')
        if features.dtype!=np.float64 or features.shape!=(333,768) or not np.isfinite(features).all():
            raise ValueError('Require the original finite float64 [333,768] text bank')
        features=np.array(features,copy=True,order='C')
    tensor_sha=hashlib.sha256(features.tobytes(order='C')).hexdigest()
    if tensor_sha!=OFFICIAL_FEATURES_SHA256:
        raise ValueError('Official feature tensor bytes differ')
    norms=np.linalg.norm(features,axis=1)
    if not np.all(np.abs(norms-1.)<1e-12):
        raise ValueError('Official bank rows are not unit-normalized')
    if file_sha256(path)!=before:
        raise ValueError('Official text-bank file changed during loading')
    return torch.from_numpy(features),{
        'text_bank_source':'original_official_333_row_file',
        'text_bank_file_sha256':before,'direct_text_sha256':tensor_sha,
        'text_bank_shape':[333,768],'text_bank_dtype':'float64',
        'text_bank_normalization':'use_stored_unit_rows_without_reencoding_or_renormalization',
        'text_bank_source_url':OFFICIAL_BANK_URL}
